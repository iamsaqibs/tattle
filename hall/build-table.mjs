#!/usr/bin/env node
// Build HALL_OF_SHAME.md from a directory of receipts (any depth: every receipt.json found is a row).
//   node hall/build-table.mjs [--draft] <receipts-dir> [out.md]
// Every cell is derived from the signed receipt body; nothing is inferred. Receipts that fail the
// structural checks are listed separately, never silently dropped. Run `tattle verify --strict <id>`
// on any row before quoting it.
import fs from 'node:fs';
import path from 'node:path';

const argv = process.argv.slice(2);
const draft = argv.includes('--draft');
const [dir, outArg] = argv.filter((a) => a !== '--draft');
if (!dir || dir === '-h' || dir === '--help') {
  console.error('usage: node hall/build-table.mjs <receipts-dir> [out.md]');
  process.exit(dir ? 0 : 2);
}
const out = outArg ?? 'HALL_OF_SHAME.md';

function* walk(d) {
  let ents;
  try {
    ents = fs.readdirSync(d, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of ents.sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (e.name === 'receipt.json') yield p;
  }
}

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const RANK = { 'NOT OBSERVED': -1, CLEAN: 0, 'PHONING HOME': 1, 'READING SECRETS': 2, 'ESCAPE CHAIN': 3 };
const rows = [];
const bad = [];
for (const file of walk(dir)) {
  try {
    const r = JSON.parse(fs.readFileSync(file, 'utf8'));
    const a = r.body.analysis;
    const hosts = (a.hosts ?? []).filter((h) => h.class !== 'local').map((h) => `${h.host} (${h.class}${h.local ? ', loopback' : ''})`);
    const sens = [...new Set((a.sensitiveReads ?? []).map((s) => (s.kind === 'clipboard' ? 'clipboard' : (s.label ?? s.rule ?? s.target))))];
    rows.push({
      id: r.id,
      tool: r.body.meta.tool.argv.map((x) => path.basename(x) === x ? x : path.basename(x)).join(' '),
      verdict: a.verdict + (a.coverage && a.coverage.rootHooked === false && a.coverage.hookedProcesses > 0 ? ' (partial coverage)' : ''),
      rank: RANK[a.verdict],
      hosts,
      sens,
      when: r.body.meta.startedAt.slice(0, 10),
      version: r.body.meta.tattleVersion,
          });
  } catch (e) {
    bad.push(`${file}: ${e.message}`);
  }
}
rows.sort((x, y) => y.rank - x.rank || x.tool.localeCompare(y.tool));

const lines = [
  ...(draft ? ['# DRAFT \u2014 not for publication; vendor notice per Ethics policy required before naming', '', '> Version probes (`--version`) are not representative of real usage. `NOT OBSERVED` means Tattle saw no Node.js process, not that the tool is clean.', ''] : []),
  '# Hall of Shame',
  '',
  'Observations, not accusations. Each row is one run of one command under [Tattle](README.md) and links to a',
  'receipt id you can re-verify (`tattle verify --strict <id>`). A verdict describes what was observed in that run;',
  'it is not a claim about intent, and absence of a finding is not proof of absence (see',
  '[limitations](docs/how-it-works.md#what-tattle-cannot-see)). Vendors get 72 hours notice before they are named',
  '(see [Ethics & disclosure](README.md#ethics--disclosure)).',
  '',
  '| Tool (command) | Verdict | Non-local hosts | Secret-shaped locations touched | Receipt |',
  '|---|---|---|---|---|',
];
for (const r of rows) {
  lines.push(`| \`${esc(r.tool)}\` | ${esc(r.verdict)} | ${esc(r.hosts.join(', ') || 'none')} | ${esc(r.sens.join(', ') || 'none')} | \`${esc(r.id)}\` |`);
}
if (!rows.length) lines.push('| _no receipts yet_ | | | | |');
lines.push('', `${rows.length} receipt(s). Generated by \`hall/build-table.mjs\` from receipts in \`${path.basename(path.resolve(dir))}\`.`);
if (bad.length) lines.push('', '## Unreadable receipts', '', ...bad.map((b) => `- ${esc(b)}`));
lines.push('');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${rows.length} row(s)${bad.length ? `, ${bad.length} unreadable` : ''}`);
